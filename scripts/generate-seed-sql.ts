/**
 * Generates supabase/seed.sql from lib/seed-data.ts so the database starts
 * with the same sample content the offline fallback shows.
 *   npm run seed:sql
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { seedCategories, seedProducts, seedProjects, seedServices, seedTestimonials } from "../lib/seed-data";

const q = (v: string | number | boolean | null | undefined) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  return `'${v.replace(/'/g, "''")}'`;
};
const arr = (a: string[]) => (a.length ? `array[${a.map(q).join(", ")}]::text[]` : "'{}'::text[]");

const out: string[] = [];
out.push(`-- =====================================================================
-- ARCHIARTIX — SAMPLE seed data (placeholder content!)
-- Generated by \`npm run seed:sql\` from lib/seed-data.ts. Safe to re-run.
-- Replace projects / products with your real work.
-- =====================================================================
`);

out.push("insert into public.categories (id, name, slug, kind, parent_id) values");
out.push(
  seedCategories.map((c) => `  (${q(c.id)}, ${q(c.name)}, ${q(c.slug)}, ${q(c.kind)}, ${q(c.parent_id)})`).join(",\n") +
    "\non conflict (id) do update set name = excluded.name, slug = excluded.slug, kind = excluded.kind;\n",
);

out.push("insert into public.projects (id, title, slug, category_id, description, location, year, area_sqft, cover_image_url, images, featured) values");
out.push(
  seedProjects
    .map(
      (p) =>
        `  (${q(p.id)}, ${q(p.title)}, ${q(p.slug)}, ${q(p.category_id)}, ${q(p.description)}, ${q(p.location)}, ${q(p.year)}, ${q(p.area_sqft)}, ${q(p.cover_image_url)}, ${arr(p.images)}, ${q(p.featured)})`,
    )
    .join(",\n") + "\non conflict (id) do nothing;\n",
);

out.push("insert into public.services (id, title, slug, summary, description, image_url, features, sort_order) values");
out.push(
  seedServices
    .map(
      (s) =>
        `  (${q(s.id)}, ${q(s.title)}, ${q(s.slug)}, ${q(s.summary)}, ${q(s.description)}, ${q(s.image_url)}, ${arr(s.features)}, ${q(s.sort_order)})`,
    )
    .join(",\n") + "\non conflict (id) do nothing;\n",
);

out.push("insert into public.products (id, name, slug, description, category_id, price_bdt, stock, images, is_published) values");
out.push(
  seedProducts
    .map(
      (p) =>
        `  (${q(p.id)}, ${q(p.name)}, ${q(p.slug)}, ${q(p.description)}, ${q(p.category_id)}, ${q(p.price_bdt)}, ${q(p.stock)}, ${arr(p.images)}, ${q(p.is_published)})`,
    )
    .join(",\n") + "\non conflict (id) do nothing;\n",
);

out.push("insert into public.testimonials (id, name, role, location, quote, rating, avatar_url, is_published, sort_order) values");
out.push(
  seedTestimonials
    .map(
      (t) =>
        `  (${q(t.id)}, ${q(t.name)}, ${q(t.role)}, ${q(t.location)}, ${q(t.quote)}, ${q(t.rating)}, ${q(t.avatar_url)}, ${q(t.is_published)}, ${q(t.sort_order)})`,
    )
    .join(",\n") + "\non conflict (id) do nothing;\n",
);

writeFileSync(join(process.cwd(), "supabase", "seed.sql"), out.join("\n"));
console.log("Wrote supabase/seed.sql");
