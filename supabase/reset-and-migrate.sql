-- ---------------------------------------------------------------------
-- Orders: only the status may change, and only along allowed transitions.
-- Cancelling an order puts its stock back.
--   pending   -> confirmed | cancelled
--   confirmed -> shipped   | cancelled
--   shipped   -> delivered
-- ---------------------------------------------------------------------
create or replace function public.guard_order_update()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  allowed boolean;
begin
  if new.id is distinct from old.id
     or new.order_no is distinct from old.order_no
     or new.user_id is distinct from old.user_id
     or new.total_bdt is distinct from old.total_bdt
     or new.shipping_address is distinct from old.shipping_address
     or new.payment_method is distinct from old.payment_method
     or new.payment_sender is distinct from old.payment_sender
     or new.payment_ref is distinct from old.payment_ref then
    raise exception 'ARX|IMMUTABLE|Only the order status can be changed.' using errcode = '23514';
  end if;

  if new.status is distinct from old.status then
    allowed := case old.status
      when 'pending'   then new.status in ('confirmed', 'cancelled')
      when 'confirmed' then new.status in ('shipped', 'cancelled')
      when 'shipped'   then new.status = 'delivered'
      else false
    end;

    if not allowed then
      raise exception 'ARX|BAD_TRANSITION|Cannot move an order from % to %.', old.status, new.status
        using errcode = '23514';
    end if;

    if new.status = 'cancelled' then
      update public.products p
         set stock = p.stock + oi.quantity
        from public.order_items oi
       where oi.order_id = new.id and oi.product_id = p.id;
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists guard_order_update on public.orders;
create trigger guard_order_update
  before update on public.orders
  for each row execute function public.guard_order_update();

-- ---------------------------------------------------------------------
-- create_order(items, shipping) — the ONLY way an order is created.
--   * requires a signed-in user
--   * rejects missing / unpublished products
--   * checks stock, computes every price from the products table
--   * decrements stock atomically (row locks, single transaction)
--   items:    [{ "product_id": "<uuid>", "quantity": 2 }, ...]
--   shipping: { "name", "phone", "address", "city", "note"? }
--   payment:  { "method": "bkash"|"nagad", "sender": "01XXXXXXXXX", "trx_id": "8N7A6D5EE1" }
-- ---------------------------------------------------------------------
drop function if exists public.create_order(jsonb, jsonb);

create or replace function public.create_order(items jsonb, shipping jsonb, payment jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  uid        uuid := auth.uid();
  item       jsonb;
  rec        record;
  prod       record;
  pid        uuid;
  qty        integer;
  merged     jsonb := '{}'::jsonb;
  total      bigint := 0;
  new_order  public.orders;
  s_name     text;
  s_phone    text;
  s_address  text;
  s_city     text;
  s_note     text;
  p_method   text;
  p_sender   text;
  p_ref      text;
begin
  if uid is null then
    raise exception 'ARX|AUTH|Please sign in to place an order.' using errcode = '28000';
  end if;

  if items is null or jsonb_typeof(items) <> 'array'
     or jsonb_array_length(items) = 0 or jsonb_array_length(items) > 50 then
    raise exception 'ARX|EMPTY|Your cart is empty.' using errcode = '22023';
  end if;

  s_name    := btrim(coalesce(shipping ->> 'name', ''));
  s_phone   := regexp_replace(coalesce(shipping ->> 'phone', ''), '[\s-]', '', 'g');
  s_address := btrim(coalesce(shipping ->> 'address', ''));
  s_city    := btrim(coalesce(shipping ->> 'city', ''));
  s_note    := nullif(btrim(coalesce(shipping ->> 'note', '')), '');

  if length(s_name) < 2 or length(s_name) > 100
     or s_phone !~ '^(\+?88)?01[3-9][0-9]{8}$'
     or length(s_address) < 8 or length(s_address) > 300
     or length(s_city) < 2 or length(s_city) > 60
     or length(coalesce(s_note, '')) > 500 then
    raise exception 'ARX|SHIPPING|Please check your delivery details.' using errcode = '22023';
  end if;

  p_method := lower(btrim(coalesce(payment ->> 'method', '')));
  p_sender := regexp_replace(coalesce(payment ->> 'sender', ''), '[\s-]', '', 'g');
  p_ref    := upper(btrim(coalesce(payment ->> 'trx_id', '')));

  if p_method not in ('bkash', 'nagad', 'cod') then
    raise exception 'ARX|PAYMENT|Choose bKash, Nagad or Cash on Delivery.' using errcode = '22023';
  end if;

  if p_method = 'cod' then
    -- pay the courier on delivery: nothing to verify up front
    p_sender := null;
    p_ref    := null;
  else
    if p_sender !~ '^(\+?88)?01[3-9][0-9]{8}$' or p_ref !~ '^[A-Z0-9]{6,20}$' then
      raise exception 'ARX|PAYMENT|Enter the bKash/Nagad number you paid from and the transaction ID.' using errcode = '22023';
    end if;
    if exists (select 1 from public.orders o where upper(o.payment_ref) = p_ref and o.status <> 'cancelled') then
      raise exception 'ARX|TRX_USED|That transaction ID has already been used on another order.' using errcode = '22023';
    end if;
  end if;

  -- merge duplicate lines
  for item in select * from jsonb_array_elements(items) loop
    begin
      pid := (item ->> 'product_id')::uuid;
      qty := (item ->> 'quantity')::integer;
    exception when others then
      raise exception 'ARX|BAD_ITEM|One of the cart items is invalid.' using errcode = '22023';
    end;
    if pid is null or qty is null or qty < 1 or qty > 99 then
      raise exception 'ARX|BAD_ITEM|One of the cart items is invalid.' using errcode = '22023';
    end if;
    merged := jsonb_set(
      merged,
      array[pid::text],
      to_jsonb(coalesce((merged ->> pid::text)::integer, 0) + qty)
    );
  end loop;

  -- pass 1: lock rows (in key order, to avoid deadlocks), validate, price
  for rec in select key, value from jsonb_each(merged) order by key loop
    select * into prod from public.products where id = rec.key::uuid for update;
    if not found or not prod.is_published then
      raise exception 'ARX|UNAVAILABLE|An item in your cart is no longer available.' using errcode = '22023';
    end if;
    qty := (rec.value #>> '{}')::integer;
    if prod.stock < qty then
      raise exception 'ARX|STOCK|Only % left of "%".', prod.stock, prod.name using errcode = '22023';
    end if;
    total := total + prod.price_bdt::bigint * qty;
  end loop;

  insert into public.orders (user_id, status, total_bdt, payment_method, payment_sender, payment_ref, customer_email, shipping_address)
  values (
    uid, 'pending', total::integer, p_method, p_sender, p_ref, auth.jwt() ->> 'email',
    jsonb_strip_nulls(jsonb_build_object(
      'name', s_name, 'phone', s_phone, 'address', s_address, 'city', s_city, 'note', s_note
    ))
  )
  returning * into new_order;

  -- pass 2: write lines and decrement stock
  for rec in select key, value from jsonb_each(merged) order by key loop
    select * into prod from public.products where id = rec.key::uuid;
    qty := (rec.value #>> '{}')::integer;

    insert into public.order_items (order_id, product_id, product_name, quantity, unit_price_bdt)
    values (new_order.id, prod.id, prod.name, qty, prod.price_bdt);

    update public.products set stock = stock - qty where id = prod.id;
  end loop;

  return jsonb_build_object(
    'id', new_order.id,
    'order_no', new_order.order_no,
    'total_bdt', new_order.total_bdt
  );
end;
$$;

revoke all on function public.create_order(jsonb, jsonb, jsonb) from public, anon;
grant execute on function public.create_order(jsonb, jsonb, jsonb) to authenticated;

