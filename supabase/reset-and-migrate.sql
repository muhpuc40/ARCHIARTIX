create or replace function public.admin_list_customers()
returns table (
  id uuid,
  full_name text,
  phone text,
  email text,
  role text,
  created_at timestamptz,
  order_count bigint,
  total_spent bigint
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'ARX|FORBIDDEN|Admins only.' using errcode = '42501';
  end if;

  return query
  select
    p.id,
    p.full_name,
    p.phone,
    u.email::text,
    p.role,
    p.created_at,
    count(o.id),
    coalesce(sum(o.total_bdt) filter (where o.status <> 'cancelled'), 0)::bigint
  from public.profiles p
  left join auth.users u on u.id = p.id
  left join public.orders o on o.user_id = p.id
  group by p.id, u.email
  order by p.created_at desc;
end;
$$;

