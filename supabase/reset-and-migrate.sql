  return jsonb_build_object(
    'products',           (select count(*) from public.products),
    'published_products', (select count(*) from public.products where is_published),
    'orders',             (select count(*) from public.orders),
    'pending_orders',     (select count(*) from public.orders where status = 'pending'),
    'revenue_bdt',        coalesce((select sum(total_bdt) from public.orders where status <> 'cancelled'), 0),
    'new_inquiries',      (select count(*) from public.inquiries where status = 'new'),
    'new_estimates',      (select count(*) from public.estimates where status = 'new'),
    'testimonials',       (select count(*) from public.testimonials),
    'low_stock',          (select count(*) from public.products where is_published and stock <= 3)
  );
end;
$$;

